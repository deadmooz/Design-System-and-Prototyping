/**
 * The design-system document every part of the platform reads and writes.
 * Extractors produce it, the workspace edits it, emitters turn it into CSS /
 * Tailwind / TS, and the prototype generator feeds a compact summary of it to
 * the LLM. JSON Schema twin: skill/design-system-prototyper/schema/design-system.schema.json
 */

export type Hex = string; // #RRGGBB or #RRGGBBAA, upper-case

export const SCALE_STEPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900'] as const;
export type ScaleStep = (typeof SCALE_STEPS)[number];
export type ColorScale = Record<ScaleStep, Hex>;

export const COLOR_ROLES = [
  'primary', 'onPrimary', 'secondary', 'accent', 'background', 'surface',
  'text', 'textMuted', 'border', 'success', 'warning', 'error', 'info',
] as const;
export type ColorRole = (typeof COLOR_ROLES)[number];

export type ColorUsage = 'background' | 'text' | 'border' | 'fill' | 'other';

export interface PaletteEntry {
  value: Hex;
  count: number;
  usage: ColorUsage[];
}

export const TYPE_STEPS = ['xs', 'sm', 'base', 'lg', 'xl', '2xl', '3xl', '4xl'] as const;
export type TypeStep = (typeof TYPE_STEPS)[number];

export interface TypeStyle {
  size: number; // px
  lineHeight: number; // unitless multiplier
  weight: number;
  letterSpacing?: number; // em
}

export type ComponentState = 'hover' | 'focus' | 'active' | 'disabled';

/** Observed styling for one UI component type, as plain CSS declarations. */
export interface ComponentSpec {
  found: boolean;
  count: number;
  selectors: string[];
  base: Record<string, string>;
  states: Partial<Record<ComponentState, Record<string, string>>>;
  variants: Record<string, Record<string, string>>;
}

export const COMPONENT_TYPES = ['button', 'input', 'card', 'badge', 'link', 'nav', 'modal', 'avatar'] as const;
export type ComponentType = (typeof COMPONENT_TYPES)[number];

export interface NavigationPattern {
  type: 'topbar' | 'sidebar' | 'none' | 'unknown';
  sticky: boolean;
  hasMobileMenu: boolean;
  hasSearch: boolean;
  items: string[];
}

export interface DesignSystem {
  version: '1';
  meta: {
    name: string;
    description?: string;
    /** `ai` = generated by a model from a written brief (ref holds the brief). */
    source: { type: 'url' | 'figma' | 'manual' | 'ai'; ref: string; extractedAt: string };
    /** 0–1: how much real evidence the extractor found (vs. defaults it filled in). */
    confidence: number;
    notes: string[];
  };
  color: {
    roles: Record<ColorRole, Hex>;
    scales: Record<string, ColorScale>;
    palette: PaletteEntry[];
  };
  typography: {
    families: { sans: string; heading: string; mono: string };
    /** Web-font stylesheet URLs (only Google Fonts URLs are loaded into previews). */
    fontSources: string[];
    scale: Record<TypeStep, TypeStyle>;
    weights: number[];
  };
  spacing: { base: number; scale: number[] };
  radius: { none: number; sm: number; md: number; lg: number; xl: number; full: number };
  shadow: { sm: string; md: string; lg: string };
  breakpoints: { sm: number; md: number; lg: number; xl: number };
  layout: { maxWidth: number; gutter: number };
  components: Partial<Record<ComponentType, ComponentSpec>>;
  patterns: { navigation: NavigationPattern; interactions: string[] };
}
